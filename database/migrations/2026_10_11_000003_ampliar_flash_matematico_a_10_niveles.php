    private function clave($a, $op1, $b, $op2, $c): string
    {
        return implode('|', [(int) $a, $op1, (int) $b, $op2 ?? '', $c === null ? '' : (int) $c]);
    }

    private function expresion($a, $op1, $b, $op2, $c): string
    {
        $signo = fn ($o) => $o === '+' ? '+' : '−';
        $txt = "{$a} " . $signo($op1) . " {$b}";
        if ($op2 !== null) $txt .= ' ' . $signo($op2) . " {$c}";
        return $txt;
